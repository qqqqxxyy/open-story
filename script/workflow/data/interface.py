"""Persistence port for workflow. Query/mapping capabilities, no flow policies."""
from abc import ABC, abstractmethod
from contextlib import AbstractContextManager
from .models import BranchView,EventOwner,DeletionContext
from script.data.base import Page,QueryPage

class StoryRepository(ABC):
    @abstractmethod
    def transaction(self) -> AbstractContextManager:...
    @abstractmethod
    def get(self,entity:str,record_id:str)->dict|None:...
    @abstractmethod
    def require(self,entity:str,record_id:str)->dict:...
    @abstractmethod
    def query(self,entity:str,filters:dict|None=None,limit:int=100,offset:int=0,descending:bool=False)->Page:...
    @abstractmethod
    def create(self,entity:str,record:dict)->dict:...
    @abstractmethod
    def update(self,entity:str,record_id:str,patch:dict)->dict:...
    @abstractmethod
    def delete(self,entity:str,record_id:str)->dict:...
    @abstractmethod
    def ensure_object(self,value:dict)->dict:...
    @abstractmethod
    def owner(self,event_id:str)->EventOwner:...
    @abstractmethod
    def append_event(self,node_id:str,object_id:str,event:dict)->dict:...
    @abstractmethod
    def select(self,node_id:str,event_id:str,selection:str)->dict:...
    @abstractmethod
    def selection_records(self,node:dict)->dict[str,dict]:...
    @abstractmethod
    def has_successors(self,node_id:str)->bool:...
    @abstractmethod
    def branch(self,branch_id:str)->BranchView:...
    @abstractmethod
    def head_owner(self,node_id:str)->BranchView|None:...
    @abstractmethod
    def assign_head(self,branch_id:str,node_id:str)->dict:...
    @abstractmethod
    def ancestor_path(self,end_node_id:str)->list[str]:...
    @abstractmethod
    def is_ancestor(self,end_node_id:str,node_id:str)->bool:...
    @abstractmethod
    def events_on_path(self,end_node_id:str,**options)->QueryPage:...
    @abstractmethod
    def node_events(self,node_id:str,**options)->Page:...
    @abstractmethod
    def deletion_context(self,node_id:str)->DeletionContext:...
    @abstractmethod
    def remove_scene(self,context:DeletionContext)->dict:...
    @abstractmethod
    def identity(self)->dict:...
    @abstractmethod
    def info(self)->dict:...
    @abstractmethod
    def close(self)->None:...
    @abstractmethod
    def records(self,entity,filters=None,fields=None,limit=None):...
    @abstractmethod
    def descendants(self,node_id,include_anchor=True):...
    @abstractmethod
    def range_deletion_context(self,node_ids):...
    @abstractmethod
    def remove_range(self,context,node_ids):...
    @abstractmethod
    def source_records(self,end_node_id,**options):...
    @abstractmethod
    def max_sequence(self,entity):...
